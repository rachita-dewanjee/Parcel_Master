-----------SHOW TRANSACTION TABLE------
CREATE OR REPLACE PROCEDURE MYPRO
IS

BEGIN
	DBMS_OUTPUT.PUT_LINE('SHOW THE LIST OF PRODUCT WHICH ARE DELIVERED---');
	DBMS_OUTPUT.PUT_LINE('--------------------');
	FOR R IN (select SUPPLIER.SUPPLIERNAME,PRODUCT.PRODUCTTYPE FROM TRANSACTIONINFO INNER JOIN SUPPLIER ON TRANSACTIONINFO.SUPPLIERID=SUPPLIER.SUPPLIERID INNER JOIN PRODUCT ON PRODUCT.PRODUCTID= SUPPLIER.PRODUCTID WHERE PRODUCT.PRODUCTSTATUS='DELIVERED') 
		LOOP
			DBMS_OUTPUT.PUT_LINE('SUPPLIERNAME: '||R.SUPPLIERNAME||'  '||'PRODUCTTYPE: '||R.PRODUCTTYPE);
		
		END LOOP;

END MYPRO;
/

BEGIN
	MYPRO;
END;
