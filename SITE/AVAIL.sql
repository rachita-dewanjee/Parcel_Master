SET SERVEROUTPUT ON;
SET VERIFY OFF;
-----------------SEARCH--------------------------------------------------------
CREATE OR REPLACE PACKAGE searchAvail AS
	
	PROCEDURE isAvailPRODUCT(p_TYPE in PRODUCT.PRODUCTTYPE%type);
END searchAvail;
/

CREATE OR REPLACE PACKAGE BODY searchAvail AS

	PROCEDURE isAvailPRODUCT(p_TYPE in PRODUCT.PRODUCTTYPE%type)
	IS

	p_id PRODUCT.PRODUCTID%type ;
	p_WEIGHT PRODUCT.PRODUCTWEIGHT%type;
	p_avail PRODUCT.PRODUCTSTATUS%type ;
	BEGIN
		select PRODUCTID,PRODUCTWEIGHT, PRODUCTSTATUS into p_id,p_WEIGHT, p_avail from PRODUCT where PRODUCTTYPE= p_TYPE;
		IF p_avail='AVAILABLE' THEN
			DBMS_OUTPUT.PUT_LINE('PRODUCT available');
		else
			DBMS_OUTPUT.PUT_LINE('PRODUCT Not available');
		end IF;
		
	END isAvailPRODUCT;	
END searchAvail;
/

ACCEPT AV CHAR PROMPT "CHECK AVAILABILITY = "

DECLARE
	PTYPE PRODUCT.PRODUCTTYPE%type;
	P PRODUCT.PRODUCTTYPE%type;
	
BEGIN
	PTYPE := '&AV';

	SELECT DISTINCT PRODUCTTYPE into P from PRODUCT where PRODUCTTYPE = PTYPE;

	searchAvail.isAvailPRODUCT(P);
	
EXCEPTION	
	WHEN NO_DATA_FOUND THEN
		DBMS_OUTPUT.PUT_LINE('PRODUCT Not EXIST');	
		
END;
