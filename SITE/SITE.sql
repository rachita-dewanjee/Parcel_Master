CREATE OR REPLACE FUNCTION myfunc(A IN SERVICEINFO.SERID%TYPE)
RETURN NUMBER
IS

PRICE SERVICEINFO.UNITPRICE%TYPE;
WEI	SERVICEINFO.SERWEIGHT%TYPE := &W;
--M NUMBER;
BEGIN
	--DBMS_OUTPUT.PUT_LINE(A);
	SELECT  UNITPRICE INTO PRICE FROM SERVICEINFO WHERE SERID=A;
	--M := PRICE  WEI;
	return PRICE*WEI; 
END myfunc;
/

