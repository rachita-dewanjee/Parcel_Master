CREATE TABLE CLIENT (
	CLIENTID int, 
	CLIENTNAME varchar2(80),
	PHONENUMBER varchar2(80),
	CEMAIL varchar2(80), 
	CADDRESS varchar2(80),
	PRODUCTID int, 
	PRIMARY KEY(CLIENTID),
	FOREIGN KEY(PRODUCTID) REFERENCES PRODUCT(PRODUCTID));

ACCEPT N6 NUMBER PROMPT "HOW MANY PRODUCT TO BE INSERTED = "
ACCEPT N9 NUMBER PROMPT "HOW MANY CLIENT TO BE INSERTED = "

	
DECLARE
	NUM PRODUCT.PRODUCTID%TYPE := 0; 
	n7 number := &N6;
	PRODUCTTYPE varchar2(80):='&PRODUCTTYPE';
    PRODUCTWEIGHT varchar2(30):='&PRODUCTWEIGHT';
	NUM1 CLIENT.CLIENTID%TYPE := 0; 
	n8 number := &n9;
	CLIENTNAME varchar2(80):='&CLIENTNAME';
    PHONENUMBER varchar2(30):='&PHONENUMBER';
	CEMAIL varchar2(80):='&CEMAIL'; 
	CADDRESS varchar2(80):='&CADDRESS';
	date_value VARCHAR2(20);
	DELIVERY_DATE VARCHAR2(20);
	C VARCHAR2(10);
BEGIN
	SELECT COUNT(PRODUCTID) INTO NUM FROM PRODUCT;
	SELECT COUNT(CLIENTID) INTO NUM1 FROM CLIENT;
	FOR i IN 1..n7 LOOP
		NUM := NUM + 1;
		NUM1 := NUM1 + 1;
		INSERT INTO PRODUCT VALUES(NUM, PRODUCTTYPE, PRODUCTWEIGHT,'AVAILABLE');
		INSERT INTO CLIENT VALUES(NUM1, CLIENTNAME, PHONENUMBER,CEMAIL,CADDRESS,NUM);
		
	END LOOP;
	
	
END;
