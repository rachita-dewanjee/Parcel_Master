SET SERVEROUTPUT ON;
SET VERIFY OFF;

clear screen;
DROP TABLE SERVICEINFO1 CASCADE CONSTRAINTS;

ACCEPT N6 NUMBER PROMPT "HOW MANY PRODUCT TO BE INSERTED = "
ACCEPT N9 NUMBER PROMPT "HOW MANY CLIENT TO BE INSERTED = "
	
DECLARE
	NUM PRODUCT.PRODUCTID%TYPE := 0; 
	n7 number := &N6;
	PRODUCTTYPE varchar2(80):='&PRODUCTTYPE';
    PRODUCTWEIGHT varchar2(30):='&PRODUCTWEIGHT';
	NUM1 CLIENT.CLIENTID%TYPE := 0; 
	n8 number := &n9;
	CLIENTNAME varchar2(80):='&CLIENTNAME';
    PHONENUMBER varchar2(30):='&PHONENUMBER';
	CEMAIL varchar2(80):='&CEMAIL'; 
	CADDRESS varchar2(80):='&CADDRESS';
BEGIN
	SELECT COUNT(PRODUCTID) INTO NUM FROM PRODUCT@site1;
	SELECT COUNT(CLIENTID) INTO NUM1 FROM CLIENT@site1;
	FOR i IN 1..n7 LOOP
		NUM := NUM + 1;
		NUM1 := NUM1 + 1;
		INSERT INTO PRODUCT@site1 VALUES(NUM, PRODUCTTYPE, PRODUCTWEIGHT,'AVAILABLE');
		INSERT INTO CLIENT@site1 VALUES(NUM1, CLIENTNAME, PHONENUMBER,CEMAIL,CADDRESS,NUM);
		
	END LOOP;
	
	
END;
/
	

